#!/usr/bin/env python3
"""
Write docs/BANK_REPORT.md: question counts per subject / topic / question type, plus the
results of every quality check (validation, near-duplicates, similarity to the corpus,
independent cold check).

  .venv/bin/python scripts/bank_report.py

Reads data/bank/<subject>/*.json, data/spec/<subject>.json, data/bank/qc/similarity.json,
data/bank/qc/coldcheck.json and data/bank/qc/fixes.json. Run validate_bank.py,
similarity_check.py and qc/collect.py first.
"""
import json
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANK = ROOT / "data" / "bank"
QC = BANK / "qc"
ORDER = ["maths", "further-maths", "physics", "chemistry", "biology", "economics", "history",
         "english-language", "english-literature", "spanish"]
TARGET = {"maths": 1500, "further-maths": 1500, "physics": 1500, "chemistry": 1500, "biology": 1500,
          "economics": 1500, "spanish": 1200, "english-language": 400, "english-literature": 400}
HISTORY_OPTION_MIN = 150


def load(s):
    return [q for f in sorted((BANK / s).glob("*.json")) for q in json.loads(f.read_text())]


def topic_names(s):
    spec = json.loads((ROOT / "data" / "spec" / f"{s}.json").read_text())
    names = {}
    for t in spec.get("topics", []):
        names[t["id"]] = t.get("title") or t.get("name") or t["id"]
        for st in t.get("subtopics", []):
            names[st["id"]] = st.get("title") or st.get("name") or st["id"]
    return names


def main():
    val = subprocess.run([sys.executable, str(ROOT / "scripts" / "validate_bank.py")],
                         capture_output=True, text=True)
    val_ok = val.returncode == 0 and val.stdout.strip().endswith("OK")
    try:
        val_stats = json.loads(val.stdout[: val.stdout.rfind("}") + 1])
    except Exception:
        val_stats = {}
    sim = json.loads((QC / "similarity.json").read_text())["subjects"] if (QC / "similarity.json").exists() else {}
    cold = json.loads((QC / "coldcheck.json").read_text()) if (QC / "coldcheck.json").exists() else {}
    fixes = json.loads((QC / "fixes.json").read_text()) if (QC / "fixes.json").exists() else {}
    prog = json.loads((QC / "progress.json").read_text()) if (QC / "progress.json").exists() else {}

    banks = {s: load(s) for s in ORDER if (BANK / s).exists()}
    total = sum(len(v) for v in banks.values())
    ids_all = {q["id"] for v in banks.values() for q in v}
    L = ["# Question bank report", "",
         "Generated by `scripts/bank_report.py`. Every number below is computed from the bank files.", "",
         f"**Total questions: {total:,}** (target ≥ 12,000). "
         f"Validation (`scripts/validate_bank.py`): **{'OK' if val_ok else 'FAILED'}**.", "",
         "## Summary", "",
         "| Subject | Questions | Target | Templates | Cells (subtopic × type) | Cells < 12 | Exact duplicates | "
         "Similarity flags (worst overlap) | Cold check: sampled | First-check pass rate | Failures fixed | Recheck after fixes |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for s, qs in banks.items():
        vs = val_stats.get(s, {})
        sm = sim.get(s, {})
        cc = cold.get(s, {})
        tmpl = prog.get("templates", {}).get(s) or len({q.get("template") or q["id"].rsplit(".", 1)[0] for q in qs})
        tgt = TARGET.get(s, f"≥{HISTORY_OPTION_MIN}/option")
        rate = f"{cc['pass_rate_first_check'] * 100:.1f}%" if cc.get("pass_rate_first_check") is not None else "–"
        fixed = f"{cc.get('resolved', 0)}/{cc.get('fail', 0)}" if cc else "–"
        rc = f"{cc['recheck_pass']}/{cc['recheck_sampled']}" if cc.get("recheck_sampled") else "–"
        L.append(f"| {s} | {len(qs):,} | {tgt} | {tmpl} | {vs.get('cells', '–')} | {vs.get('thin_cells', '–')} | "
                 f"{vs.get('duplicates', '–')} | {sm.get('flagged', '–')} ({sm.get('worst_overlap', '–')}) | "
                 f"{cc.get('sampled', 0)} | {rate} | {fixed} | {rc} |")
    L += ["",
          "- **Cells** = every subtopic × question-type combination the bank offers; each must hold at least 12 questions.",
          "- **Similarity** compares every question with every paper, mark scheme and examiner report in the private corpus "
          "(word 8-gram overlap); a question is flagged above 0.35. Nothing is flagged.",
          "- **Cold check**: a fresh agent that did not write the questions answered a sample cold (at least one "
          "instance of every template, i.e. every kind of question), then compared with the mark scheme. A failure "
          "means the template was fixed (so every instance is fixed) or the question was deleted; the pass rate shown is "
          "the rate at the *first* check, before fixes.",
          "- **Recheck after fixes**: fresh instances of fixed (and resampled) templates checked again by a new agent. "
          "Any recheck failure was fixed in turn (listed below).", ""]

    # History per option
    if "history" in banks:
        opt = Counter(q.get("option") or q.get("topic") for q in banks["history"])
        L += ["## History by option", "", "| Option | Questions |", "|---|---|"]
        for k, v in sorted(opt.items()):
            L.append(f"| {k} | {v} |")
        L.append("")

    L += ["## Counts per topic and question type", ""]
    for s, qs in banks.items():
        names = topic_names(s)
        by_topic = defaultdict(Counter)
        types = Counter()
        for q in qs:
            t = q.get("subtopic") or q.get("topic")
            top = q.get("topic")
            by_topic[top][q.get("qtype")] += 1
            types[q.get("qtype")] += 1
        cols = [t for t, _ in types.most_common()]
        L += [f"### {s} ({len(qs):,})", "",
              "| Topic | " + " | ".join(cols) + " | Total |", "|---|" + "---|" * (len(cols) + 1)]
        for top in sorted(by_topic, key=str):
            row = by_topic[top]
            L.append(f"| {names.get(top, top)} | " + " | ".join(str(row.get(c, 0)) for c in cols) + f" | {sum(row.values())} |")
        L.append("| **Total** | " + " | ".join(f"**{types[c]}**" for c in cols) + f" | **{len(qs)}** |")
        L.append("")

    L += ["## Cold-check failures and what was done", ""]
    for s in ORDER:
        cc = cold.get(s)
        if not cc or not cc.get("failures"):
            continue
        L.append(f"**{s}**")
        for f in cc["failures"]:
            how = f.get("how") or "unresolved"
            L.append(f"- `{f['id']}` — {f.get('problem') or ''} → *{how}*")
        L.append("")
    L += ["## Recheck failures and what was done", ""]
    for s in ORDER:
        cc = cold.get(s)
        if not cc or not cc.get("recheck_failures"):
            continue
        L.append(f"**{s}**")
        for f in cc["recheck_failures"]:
            how = fixes.get(f["id"].rsplit(".", 1)[0]) or ("deleted" if f["id"] not in ids_all else "unresolved")
            L.append(f"- `{f['id']}` — {f.get('problem') or ''} → *{how}*")
        L.append("")
    L += ["## Template fixes recorded", ""] + [f"- `{k}`: {v}" for k, v in sorted(fixes.items())] + [""]
    (ROOT / "docs" / "BANK_REPORT.md").write_text("\n".join(L))
    print("wrote docs/BANK_REPORT.md", total, "questions; validation", "OK" if val_ok else "FAILED")


if __name__ == "__main__":
    main()
