def sub_id(topic, sub):
    return f"biology.{topic}.{sub}"


def build():
    topics = []
    for tid, tref, ttitle, subs in TREE:
        st_out = []
        for sid, sref, stitle, summ, qts, pts in subs:
            papers = ["1B", "2B"] if any(not r.endswith("B") for r, _ in pts) else ["2B"]
            st_out.append({
                "id": sub_id(tid, sid), "ref": sref, "title": stitle, "summary": summ,
                "papers": papers, "qtypes": qts,
                "points": [dict({"ref": r, "summary": s}, **({"paper2_only": True} if r.endswith("B") else {}))
                           for r, s in pts],
            })
        topics.append({"id": tid, "ref": tref, "title": ttitle, "papers": ["1B", "2B"], "subtopics": st_out})
    spec = {
        "subject": "biology", "code": "4BI1", "board": "Pearson Edexcel",
        "title": "International GCSE Biology (9-1)", "short": "Biology",
        "official_url": "https://qualifications.pearson.com/en/qualifications/edexcel-international-gcses/international-gcse-biology-2017.html",
        "spec_url": "https://qualifications.pearson.com/en/qualifications/edexcel-international-gcses/international-gcse-biology-2017.html",
        "papers": PAPERS, "qtypes": QTYPES, "topics": topics,
    }
    out = ROOT / "data" / "spec" / "biology.json"
    out.write_text(json.dumps(spec, ensure_ascii=False, indent=1))
    return spec


def sub_lookup():
    """subtopic id -> (topic id, set of point refs, qtypes)"""
    out = {}
    for tid, _, _, subs in TREE:
        for sid, _, _, _, qts, pts in subs:
            out[sub_id(tid, sid)] = (tid, [r for r, _ in pts], qts)
    return out
